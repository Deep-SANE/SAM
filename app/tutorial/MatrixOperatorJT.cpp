// MatrixOperatorJT: the low-lying spectrum of a nucleus in the U(3)xU(4)
// symmetry-adapted basis.
//
// For a nucleus (Z protons, N neutrons), total angular momentum J and model
// space Nmax, the program
//   1. builds the basis (optionally truncated, see below),
//   2. computes the matrix of an operator, usually a Hamiltonian,
//   3. finds its lowest eigenvalues and eigenvectors,
//   4. optionally prints the U(3) and U(4) content of the lowest states and
//      saves the eigenpairs, which WavefunctionAnalyzer and ObservablesJT read.
//
// The operator's expansion files must be in the data directory: the released
// ones come with `make data` (for the default below: make data
// OPS="N2LO_opt_bare Kinetic CoMNumberOp").
//
// Do not edit this file; copy it into app/work/ and edit the copy:
//   cp app/tutorial/MatrixOperatorJT.cpp app/work/
//   make -j 8 apps && mpirun -np 1 bin/work/MatrixOperatorJT
// Matrix elements are computed in parallel with MPI and OpenMP, so more MPI
// ranks (mpirun -np 4 ...) shorten large runs.

#include <algorithm>
#include <chrono>
#include <iostream>
#include <string>
#include <vector>

#include <eigensolver.h>
#include <print.h>
#include <readwrite.h>

#include <sam.h>
#include <OperatorJT.h>
#include <WavefunctionAnalyzer.h>

int main(int argc, char* argv[])
{
  using utils::print;

  sam::initialize(&argc, &argv);

  ////////////// SETTINGS //////////////

  // nucleus, J (doubled: JJ = 2J), model space and HO energy hw (MeV):
  int Z = 3, N = 3, JJ = 2, Nmax = 4, hw = 20;

  // the operator:
  //   "Hamiltonian with <interaction>": relative kinetic energy + the
  //     interaction + a Lawson term that pushes spurious center-of-mass
  //     excitations up. Released interactions (make data-list):
  //     N2LO_opt_bare, N2LO_opt_srg2.0, N2LO_sat_bare, N3LO_EMN500_bare,
  //     N4LO_EMN500_bare, N3LO_EM500_srg2.0
  //   or any scalar operator, e.g. "L.L", "L.S", "Kinetic", "CoMNumberOp"
  std::string name = "Hamiltonian with N2LO_opt_bare";

  int n_states = 5;      // number of lowest eigenpairs
  bool analyze = true;   // print U(3) and U(4) probabilities of the lowest
  int n_analyze = 2;     //   n_analyze states
  bool write = true;     // save the eigenpairs in the data directory, for
                         //   WavefunctionAnalyzer and ObservablesJT

  // optional truncation. Each hw_subspace selects, in the N hw excitation,
  // the U(3) irreps, U(4) irreps, spins SS = 2S and isospins TT = 2T to keep;
  // an empty list keeps all of them, and an excitation that is not listed is
  // kept whole. Irreps are written as the analysis (analyze = true) prints
  // them. The example keeps only isospin T = TT/2 in every excitation:
  bool truncate = false;
  int TT = 0;
  std::vector<U3xU4::hw_subspace> subspaces;
  for (int n = Nmax % 2; n <= Nmax; n += 2)
    subspaces.emplace_back(n, u3::irreps{}, u4::irreps{},
                           std::vector<HO::qn_t>{},
                           std::vector<HO::qn_t>{static_cast<HO::qn_t>(TT)});
  // a truncated space saves its eigenpairs in a folder of its own:
  std::string custom_dir = "Truncation_TT" + std::to_string(TT);

  ////////////// DON'T EDIT ANYTHING BELOW //////////////

#ifdef USE_MPI
  int mpi_rank = 0;
  MPI_Comm_rank(MPI_COMM_WORLD, &mpi_rank);
  const bool root = (mpi_rank == 0);
#else
  const bool root = true;
#endif

  // basis (no subspaces = the full Nmax space):
  if (!truncate) subspaces.clear();
  U3xU4::ManyNucleonBasis basis(N, Z, Nmax, JJ, subspaces);
  basis.construct();

  if (root)
  {
    print("Z = {}, N = {}, J = {}/2, Nmax = {}, hw = {} MeV, {}\n", Z, N, JJ,
          Nmax, hw, truncate ? "truncated" : "full space");
    print("Basis dimension: {}\n", basis.dim());
  }

  HO::Table_nljmjmt HO_labels(basis.maxShell());
  U3xU4::Table_gelfand gelfand_labels(basis.maxShell());

  JT::Operator op(name, N, Z, hw, Nmax, HO_labels, gelfand_labels);
  if (root) op.is();

  // matrix (each MPI rank holds a block of rows):
  auto t0 = std::chrono::steady_clock::now();
  auto mat = op.matrix_CSR(basis);
  auto t1 = std::chrono::steady_clock::now();

  // lowest eigenpairs:
  n_states = std::max(1, std::min<int>(n_states, basis.dim()));
  auto [evals, evecs] =
      utils::eigensolver_symmetric_spectra(mat, n_states, 1e-10, 100000);
  auto t2 = std::chrono::steady_clock::now();

  if (root)
  {
    print("Eigenvalues (MeV):\n");
    for (size_t i = 0; i < evals.size(); i++)
      print("  {:3}  {:14.6f}\n", i, evals[i]);

    if (write)
    {
      auto wfns_file = truncate ? op.wfns_file(basis, custom_dir)
                                : op.wfns_file(basis);
      utils::writeEigenPairs(wfns_file, evals, evecs);
      print("Eigenpairs written to {}\n", wfns_file);
    }

    if (analyze)
    {
      int n = std::min<int>(n_analyze, evecs.cols());
      print("U(3) and U(4) probabilities of the lowest {} states:\n", n);

      for (const auto& subspace : sam::U3_wavefunction_analyzer(basis, evecs, n))
        std::cout << subspace << std::endl;

      for (const auto& subspace : sam::U4_wavefunction_analyzer(basis, evecs, n))
        std::cout << subspace << std::endl;
    }

    std::chrono::duration<double> t_mat = t1 - t0, t_eig = t2 - t1;
    print("Time: matrix {:.1f} s, eigenpairs {:.1f} s\n", t_mat.count(),
          t_eig.count());
  }

  sam::finalize();
}
