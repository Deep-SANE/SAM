// ObservablesJT: observables from eigenstates saved by MatrixOperatorJT.
//
// (1) one nucleus: expectation values of an operator in the lowest states,
//     and transition strengths between them (same J);
// (2) two nuclei: a transition from the ground state of one nucleus to the
//     ground state of another, e.g. the Gamow-Teller beta decay
//     6He(0+) -> 6Li(1+).
//
// First run MatrixOperatorJT with write = true (its default) for every
// nucleus and J used here, with the same Hamiltonian, Nmax, hw and
// truncation; the defaults below match its defaults (6Li, J = 1, Nmax = 4).
// For (2) also run it for 6He, J = 0. The operator's expansion must be in the
// data directory (make data OPS="Radius E2 M1 GamowTellerMinus").
//
// Do not edit this file; copy it into app/work/ and edit the copy:
//   cp app/tutorial/ObservablesJT.cpp app/work/
//   make -j 8 apps && mpirun -np 1 bin/work/ObservablesJT
//
// What is printed (JT::Operator::expectationValue, transitionStrength):
//   Radius, Radius_p,  rms point-nucleon, -proton, -neutron radius (fm), with
//   Radius_n           the HO center-of-mass part removed
//   M1                 magnetic moment mu (mu_N)
//   other operators    <J, M = J| O |J, M = J> (E2: the zero component, e fm^2)
//   B(E2), B(M1)       reduced transition strengths in e^2 fm^4 and mu_N^2,
//                      from J_i to J_f
//   Gamow-Teller       the reduced matrix element <f||sigma t||i>; then
//                      B(GT) = |<f||sigma t||i>|^2 / (2 J_i + 1)
//   Fermi              <f| T_-+ |i>

#include <chrono>
#include <iostream>
#include <string>
#include <utility>
#include <vector>

#include <print.h>
#include <readwrite.h>

#include <sam.h>
#include <OperatorJT.h>

namespace
{
  // a nucleus and its model space, as in the MatrixOperatorJT run:
  struct Nucleus
  {
    int Z, N, JJ;
    int TT = -1;   // isospin truncation (truncate = true, TT) or -1: none
  };

  // the basis of that run (truncated to isospin TT/2 if TT >= 0):
  U3xU4::ManyNucleonBasis make_basis(const Nucleus& x, int Nmax)
  {
    std::vector<U3xU4::hw_subspace> subspaces;
    if (x.TT >= 0)
      for (int n = Nmax % 2; n <= Nmax; n += 2)
        subspaces.emplace_back(
            n, u3::irreps{}, u4::irreps{}, std::vector<HO::qn_t>{},
            std::vector<HO::qn_t>{static_cast<HO::qn_t>(x.TT)});
    U3xU4::ManyNucleonBasis basis(x.N, x.Z, Nmax, x.JJ, subspaces);
    basis.construct();
    return basis;
  }

  // the eigenpairs saved by MatrixOperatorJT for this nucleus:
  auto read_eigenpairs(const std::string& hamiltonian, const Nucleus& x,
                       const U3xU4::ManyNucleonBasis& basis, int Nmax, int hw,
                       const HO::Table_nljmjmt& HO_labels,
                       const U3xU4::Table_gelfand& gelfand_labels)
  {
    JT::Operator H(hamiltonian, x.N, x.Z, hw, Nmax, HO_labels, gelfand_labels);
    std::string file =
        (x.TT >= 0) ? H.wfns_file(basis, "Truncation_TT" + std::to_string(x.TT))
                    : H.wfns_file(basis);
    auto eigenpairs = utils::readEigenPairs(file);   // (eigenvalues, vectors)
    if (static_cast<size_t>(eigenpairs.second.rows()) != basis.dim())
      throw std::runtime_error(
          "Sorry, the eigenvectors in " + file + " do not match this basis; "
          "use the settings of the MatrixOperatorJT run that wrote them");
    return eigenpairs;
  }
}

int main(int argc, char* argv[])
{
  using utils::print;

  sam::initialize(&argc, &argv);

  ////////////// SETTINGS //////////////

  // the run of MatrixOperatorJT that saved the eigenpairs:
  std::string hamiltonian = "Hamiltonian with N2LO_opt_bare";
  int Nmax = 4, hw = 20;

  // (1) one nucleus (Z, N, JJ = 2J[, TT for a T-truncated run]):
  bool one_nucleus = true;
  Nucleus nucleus = {3, 3, 2};   // 6Li, J = 1
  int n_states = 2;              // expectation values in the lowest states
  // operators for expectation values (see the top of the file), e.g.
  // "Radius", "Radius_p", "Radius_n", "E2", "M1", "NumberOp":
  std::vector<std::string> moments = {"Radius", "E2", "M1"};
  // transitions (initial state, final state) for B(E2), B(M1):
  std::vector<std::pair<int, int>> transitions = {{0, 1}};
  std::vector<std::string> transition_ops = {"E2", "M1"};

  // (2) two nuclei: ground state of `initial` -> ground state of `target`
  bool two_nuclei = false;
  Nucleus initial = {2, 4, 0};   // 6He, J = 0
  Nucleus target = {3, 3, 2};    // 6Li, J = 1
  // "GamowTellerMinus", "GamowTellerPlus", "FermiMinus", "FermiPlus",
  // or "E2", "M1" between two J of the same nucleus:
  std::string transition_op = "GamowTellerMinus";

  ////////////// DON'T EDIT ANYTHING BELOW //////////////

#ifdef USE_MPI
  int mpi_rank = 0;
  MPI_Comm_rank(MPI_COMM_WORLD, &mpi_rank);
  const bool root = (mpi_rank == 0);
#else
  const bool root = true;
#endif

  auto t0 = std::chrono::steady_clock::now();

  if (one_nucleus)
  {
    auto basis = make_basis(nucleus, Nmax);
    HO::Table_nljmjmt HO_labels(basis.maxShell());
    U3xU4::Table_gelfand gelfand_labels(basis.maxShell());

    auto [evals, evecs] = read_eigenpairs(hamiltonian, nucleus, basis, Nmax,
                                          hw, HO_labels, gelfand_labels);
    n_states = std::min<int>(n_states, evecs.cols());

    if (root)
    {
      print("Z = {}, N = {}, J = {}/2, Nmax = {}, hw = {} MeV: {} states\n",
            nucleus.Z, nucleus.N, nucleus.JJ, Nmax, hw, basis.dim());
      for (int i = 0; i < n_states; i++)
        print("  state {}: E = {:.6f} MeV\n", i, evals[i]);
    }

    // expectation values <i| O |i>:
    std::vector<std::pair<JT::Operator::Col_t, JT::Operator::Col_t>> diag;
    for (int i = 0; i < n_states; i++)
      diag.emplace_back(evecs.col(i), evecs.col(i));

    for (const auto& name : moments)
    {
      JT::Operator op(name, nucleus.N, nucleus.Z, hw, Nmax, HO_labels,
                      gelfand_labels);
      auto values = op.expectationValue(basis, diag);
      if (root)
        for (int i = 0; i < n_states; i++)
          print("  <{}| {} |{}> = {:.6f}\n", i, name, i, values[i]);
    }

    // transition strengths i -> f (pairs are (final, initial) states):
    std::vector<std::pair<int, int>> done;
    std::vector<std::pair<JT::Operator::Col_t, JT::Operator::Col_t>> pairs;
    for (const auto& [i, f] : transitions)
      if (i < evecs.cols() && f < evecs.cols())
      {
        pairs.emplace_back(evecs.col(f), evecs.col(i));
        done.emplace_back(i, f);
      }

    for (const auto& name : transition_ops)
    {
      JT::Operator op(name, nucleus.N, nucleus.Z, hw, Nmax, HO_labels,
                      gelfand_labels);
      auto values = op.transitionStrength(basis, pairs);
      if (root)
        for (size_t k = 0; k < values.size(); k++)
          print("  B({}; {} -> {}) = {:.6f}\n", name, done[k].first,
                done[k].second, values[k]);
    }
  }

  if (two_nuclei)
  {
    auto kets = make_basis(initial, Nmax), bras = make_basis(target, Nmax);
    int maxShell = std::max(kets.maxShell(), bras.maxShell());
    HO::Table_nljmjmt HO_labels(maxShell);
    U3xU4::Table_gelfand gelfand_labels(maxShell);

    auto [evals_i, evecs_i] = read_eigenpairs(hamiltonian, initial, kets, Nmax,
                                              hw, HO_labels, gelfand_labels);
    auto [evals_f, evecs_f] = read_eigenpairs(hamiltonian, target, bras, Nmax,
                                              hw, HO_labels, gelfand_labels);

    JT::Operator op(transition_op, initial.N, initial.Z, hw, Nmax, HO_labels,
                    gelfand_labels);
    auto values =
        op.transitionStrength(bras, kets, {{evecs_f.col(0), evecs_i.col(0)}});

    if (root)
    {
      print("(Z, N, J) = ({}, {}, {}/2), E = {:.6f} MeV  ->  "
            "({}, {}, {}/2), E = {:.6f} MeV\n",
            initial.Z, initial.N, initial.JJ, evals_i[0], target.Z, target.N,
            target.JJ, evals_f[0]);
      print("  {}: {:.6f}\n", transition_op, values[0]);
    }
  }

  if (root)
  {
    std::chrono::duration<double> t = std::chrono::steady_clock::now() - t0;
    print("Time: {:.1f} s\n", t.count());
  }

  sam::finalize();
}
