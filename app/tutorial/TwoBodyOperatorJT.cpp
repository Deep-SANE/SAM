// TwoBodyOperatorJT: expand a two-body operator into U(3)xU(4) tensors and
// write the expansion file that SAM reads in later calculations, or extend an
// existing file to a larger maxShell.
//
// Most users never need this: the expansions of the released interactions
// and operators come with `make data` (see make data-list). Run it for an
// operator that is not released, or to reach a larger maxShell than the
// released file. Two-body expansions are expensive (hours to days for
// realistic interactions at maxShell >= 10), so run them on a cluster:
// matrix elements are spread over MPI ranks and OpenMP threads.
//
// Do not edit this file; copy it into app/work/ and edit the copy:
//   cp app/tutorial/TwoBodyOperatorJT.cpp app/work/
//   make -j 8 apps && mpirun -np 4 bin/work/TwoBodyOperatorJT
//
// The file is
//   <data dir>/TwoBodyOperatorJT/<name>/Expansion/<name>_hw<hw>
// It holds the pairs of up to maxShell HO quanta; a nucleus with valence
// shell v at Nmax needs pairs of up to 2v + Nmax quanta (4He: Nmax; p-shell
// nuclei: Nmax + 2). If the file exists and already reaches maxShell, there
// is nothing to do; if it reaches a smaller maxShell, only the new tensors
// are computed and appended. A released file is read-only and must be
// unlocked first (chmod u+w <file>).
//
// Only one two-body operator per program run: the m-scheme matrix elements
// are cached in a single shared cache (HO::twbme_mscheme_cache()) that is
// correct for one operator only.

#include <chrono>
#include <cstdint>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <set>
#include <string>

#include <print.h>

#include <sam.h>
#include <ExpansionFiles.h>
#include <TwoBodyOperatorJT.h>

int main(int argc, char* argv[])
{
  using utils::print;

  sam::initialize(&argc, &argv);

  ////////////// SETTINGS //////////////

  // the operator; SAM computes these itself:
  //   "L.L", "L.S"     two-body parts of L.L and L.S
  //   "Kinetic"        two-body part of the relative kinetic energy
  //   "CoMNumberOp"    two-body part of the CoM HO number operator
  //   "Rrel"           two-body part of the intrinsic radius squared
  // any other name is a two-body interaction read from its matrix-element
  // file in <data dir>/Ab-initio_Interactions (not released with SAM), e.g.
  //   "N2LO_opt_bare", "N2LO_opt_srg2.0", "N3LO_EMN500_bare", ...
  std::string name = "L.S";

  // pairs of up to maxShell HO quanta (see above):
  int maxShell = 4;

  // HO energy (MeV). Keep hw = 20 for the operators SAM computes itself:
  // their expansion is stored once at 20 MeV and rescaled to any hw when
  // read. An interaction file has its own hw.
  int hw = 20;

  ////////////// DON'T EDIT ANYTHING BELOW //////////////

  int mpi_rank = 0, mpi_size = 1;
  MPI_Comm_rank(MPI_COMM_WORLD, &mpi_rank);
  MPI_Comm_size(MPI_COMM_WORLD, &mpi_size);
  const bool root = (mpi_rank == 0);

  const std::set<std::string> computed_by_sam = {"L.L", "L.S", "Kinetic",
                                                 "CoMNumberOp", "Rrel"};
  if (computed_by_sam.count(name) && hw != 20)
    throw std::invalid_argument(
        "Sorry, " + name + " is expanded at hw = 20 MeV only (SAM rescales "
        "it to other hw when reading); set hw = 20");

  HO::Table_nljmjmt HO_labels(maxShell);
  U3xU4::Table_gelfand gelfand_labels(maxShell);

  // a reusable expansion has no valence shell and Nmax = maxShell:
  JT::TwoBodyOperator op(name, hw, maxShell, 0, maxShell, HO_labels,
                         gelfand_labels);
  if (root) op.is();

  std::string filename = op.dirname() + "/Expansion/" + name + "_hw" +
                         std::to_string(hw);

  // maxShell of an existing file (its first byte), or -1:
  int maxShell_file = -1;
  if (std::filesystem::exists(filename))
  {
    std::ifstream s(filename, std::ios::binary);
    int8_t m = -1;
    s.read(reinterpret_cast<char*>(&m), 1);
    maxShell_file = s ? m : -1;
  }

  if (maxShell_file >= maxShell)
  {
    if (root)
      print("{}\nalready reaches maxShell = {}; nothing to do.\n", filename,
            maxShell_file);
    sam::finalize();
    return 0;
  }

  if (root)
  {
    if (maxShell_file >= 0)
      print("Extending\n  {}\nfrom maxShell = {} to {} on {} MPI ranks\n",
            filename, maxShell_file, maxShell, mpi_size);
    else
      print("Expanding up to maxShell = {} on {} MPI ranks into\n  {}\n",
            maxShell, mpi_size, filename);
  }

  auto t0 = std::chrono::steady_clock::now();

  if (maxShell_file >= 0)   // a reusable file has Nmax = maxShell
    op.expand_exist_MPI(filename, maxShell_file, maxShell_file);
  else
    op.expand_new_MPI(filename);

  auto t1 = std::chrono::steady_clock::now();

  if (root)
  {
    std::chrono::duration<double> t = t1 - t0;
    print("Done: {} reaches maxShell = {}. Time: {:.1f} s\n", filename,
          maxShell, t.count());
  }

  sam::finalize();
}
