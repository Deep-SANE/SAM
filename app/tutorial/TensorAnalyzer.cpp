// TensorAnalyzer: what an operator expansion is made of.
//
// Reads the expansion file of a one- or two-body operator and groups its
// tensors by U(3) irrep, U(4) irrep, orbital rank LL = 2L and spin rank
// SS = 2S. For each group it prints statistics of the strengths (min, max,
// mean, standard deviation), which show which symmetries dominate the
// operator; the same tables are written next to the expansion, in
//   <data dir>/<OneBody|TwoBody>OperatorJT/<name>/Analysis/
//
// The expansion file must be in the data directory (make data, or
// OneBodyOperatorJT / TwoBodyOperatorJT), up to at least maxShell below.
//
// Do not edit this file; copy it into app/work/ and edit the copy:
//   cp app/tutorial/TensorAnalyzer.cpp app/work/
//   make -j 8 apps && mpirun -np 1 bin/work/TensorAnalyzer

#include <iostream>
#include <string>

#include <sam.h>
#include <OneBodyOperatorJT.h>
#include <TwoBodyOperatorJT.h>

namespace
{
  // print the four groupings of the tensors of op:
  template <class Operator>
  void analyze(Operator& op, bool root)
  {
    auto u3 = op.U3_tensor_analyzer_write();
    auto u4 = op.U4_tensor_analyzer_write();
    auto LL = op.LL_tensor_analyzer_write();
    auto SS = op.SS_tensor_analyzer_write();
    if (!root) return;

    std::cout << "by U(3) irrep:" << std::endl;
    for (const auto& [irr, stats] : u3)
      std::cout << "  " << irr << ":\t" << stats << std::endl;

    std::cout << "by U(4) irrep:" << std::endl;
    for (const auto& [irr, stats] : u4)
      std::cout << "  " << irr << ":\t" << stats << std::endl;

    std::cout << "by orbital rank LL = 2L:" << std::endl;
    for (const auto& [LL_, stats] : LL)
      std::cout << "  " << LL_ << ":\t" << stats << std::endl;

    std::cout << "by spin rank SS = 2S:" << std::endl;
    for (const auto& [SS_, stats] : SS)
      std::cout << "  " << SS_ << ":\t" << stats << std::endl;
  }
}

int main(int argc, char* argv[])
{
  sam::initialize(&argc, &argv);

  ////////////// SETTINGS //////////////

  int body = 2;               // 1: one-body, 2: two-body operator
  std::string name = "N2LO_opt_bare";
  int maxShell = 4;           // analyze the tensors up to this shell
  int hw = 20;                // the hw of the expansion file

  ////////////// DON'T EDIT ANYTHING BELOW //////////////

#ifdef USE_MPI
  int mpi_rank = 0;
  MPI_Comm_rank(MPI_COMM_WORLD, &mpi_rank);
  const bool root = (mpi_rank == 0);
#else
  const bool root = true;
#endif

  HO::Table_nljmjmt HO_labels(maxShell);
  U3xU4::Table_gelfand gelfand_labels(maxShell);

  if (body == 1)
  {
    JT::OneBodyOperator op(name, hw, maxShell, 0, maxShell, HO_labels,
                           gelfand_labels);
    if (root) op.is();
    analyze(op, root);
  }
  else
  {
    JT::TwoBodyOperator op(name, hw, maxShell, 0, maxShell, HO_labels,
                           gelfand_labels);
    if (root) op.is();
    analyze(op, root);
  }

  sam::finalize();
}
