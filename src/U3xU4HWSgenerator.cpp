  UNxU4::SlaterDeterminants expand_to_SD(const U3xU4::GammaElement& G, 
    const u3::gelfands& sps3, const u4::gelfands& sps4)
  {
    int A = G.particles(), n = G.shell(), N = (n + 1) * (n + 2) / 2;

    UNxU4::SlaterDeterminants SDarr;

    // an array to store the position of the particles
    std::vector<size_t> pos(A);
    // initialize first combination: 0, 1, ..., A-1
    for (size_t i = 0; i < A; ++i) pos[i] = i;

    while (true)
    {
      int N12b = 0, N11b = 0, N13p = 0, N12p = 0, N11p = 0;
      for (const auto& index : pos)
      {
        size_t r = index / N, c = index % N;

        N12b += sps3[c].n12();
        N11b += sps3[c].n11();

        N13p += sps4[r].n13();
        N12p += sps4[r].n12();
        N11p += sps4[r].n11();
      }

      if (N12b == (G.n13() + G.n23()) && N11b == G.n13() &&
          N13p == (G.n14() + G.n24() + G.n34()) &&
          N12p == (G.n14() + G.n24()) && N11p == G.n14())
      {
        UNxU4::SlaterDeterminant SD(n);
        // fill SD with positions
        for (const auto& index : pos)
        {
          size_t r = index / N, c = index % N;
          // std::cout << r << c << std::endl;
          SD.occupy(r, c);
        }

        SDarr.push_back(SD);
      }

      // Generate next combination
      size_t i = A; // start from the right end
      while (i > 0 && pos[i - 1] == 4 * N - A + i - 1)
        i--; // find the rightmost element that can be incremented

      if (i == 0) break; // if no element can be increased, done

      pos[i - 1]++; // increase the first non-maxed-out position

      for (size_t j = i; j < A; ++j)
        pos[j] = pos[j - 1] + 1; // ensure the combination remains increasing
    }

    return SDarr;
  }

  static auto RaisingGenerator(UNxU4::SlaterDeterminants& SDarr,
    const u3::gelfands& sps3, const u4::gelfands& sps4)
  {
    /* Acting a raising generator on the expansion of SDs will result in
       a new expansion of SDs, each of which has vanishing coefficient.
       Thus, a pair of a raising generator and a new SD defines a homogeneous
       linear equation. Our task is to solve all these linear equations
       generated by all raising generators.
       To keep track of the generators, I will label them as
       E12b = 0, E23b = 1,
       E12p = 2, E23p = 3, E34p = 4
    */

    std::vector<std::pair<size_t, UNxU4::SlaterDeterminant>> opt_SD;

#ifdef NULLSPACE_SPARSE
    std::vector<Eigen::Triplet<double>> ija;
#else
    std::vector<Eigen::RowVectorXd> mat_temp;
#endif

    // Looping over all SDs
    for (size_t i = 0; i < SDarr.size(); i++)
    {
      // Going through occupied bits
      for (size_t index = SDarr[i].bits().find_first();
           index != boost::dynamic_bitset<>::npos;
           index = SDarr[i].bits().find_next(index))
      {
        // convert flat index to (r, c)
        auto [r, c] = SDarr[i].invert_index(index); 

        // action of E12b
        int c12 = -1;
        for (int g = 0; g < sps3.size(); g++)
          if (u3::E12(sps3[c], sps3[g]))
          {
            c12 = g;
            break;
          }
        if (c12 >= 0 &&
            !SDarr[i].is_occupied(r, c12)) // meaning it finds a new state
        {
          UNxU4::SlaterDeterminant sd = SDarr[i];
          double phase = (sd.num_hop(r, c, r, c12) % 2 == 0) ? 1 : -1;
          sd.vacate(r, c);
          sd.occupy(r, c12);
          std::pair<size_t, UNxU4::SlaterDeterminant> p(0, sd);
          auto it = std::find(opt_SD.begin(), opt_SD.end(), p);
          if (it == opt_SD.end())
          {
#ifdef NULLSPACE_SPARSE
            ija.emplace_back(opt_SD.size(), i, phase * sps3[c].e12());
#else
            Eigen::RowVectorXd x(SDarr.size());
            x.setZero();
            x(i) = phase * sps3[c].e12();
            mat_temp.push_back(x);
#endif
            opt_SD.push_back(p);
          }
          else
          {
#ifdef NULLSPACE_SPARSE
            ija.emplace_back(std::distance(opt_SD.begin(), it), i,
                             phase * sps3[c].e12());
#else
            mat_temp[std::distance(opt_SD.begin(), it)](i) =
                phase * sps3[c].e12();
#endif
          }
        }

        // action of E23b
        int c23 = -1;
        for (int g = 0; g < sps3.size(); g++)
          if (u3::E23_12(sps3[c], sps3[g]))
          {
            c23 = g;
            break;
          }
        if (c23 >= 0 &&
            !SDarr[i].is_occupied(r, c23)) // meaning it finds a new state
        {
          UNxU4::SlaterDeterminant sd = SDarr[i];
          double phase = (sd.num_hop(r, c, r, c23) % 2 == 0) ? 1 : -1;
          sd.vacate(r, c);
          sd.occupy(r, c23);
          std::pair<size_t, UNxU4::SlaterDeterminant> p(1, sd);
          auto it = std::find(opt_SD.begin(), opt_SD.end(), p);
          if (it == opt_SD.end())
          {
#ifdef NULLSPACE_SPARSE
            ija.emplace_back(opt_SD.size(), i, phase * sps3[c].e23_12());
#else
            Eigen::RowVectorXd x(SDarr.size());
            x.setZero();
            x(i) = phase * sps3[c].e23_12();
            mat_temp.push_back(x);
#endif
            opt_SD.push_back(p);
          }
          else
          {
#ifdef NULLSPACE_SPARSE
            ija.emplace_back(std::distance(opt_SD.begin(), it), i,
                             phase * sps3[c].e23_12());
#else
            mat_temp[std::distance(opt_SD.begin(), it)](i) =
                phase * sps3[c].e23_12();
#endif
          }
        }

        // action of E12p
        int r12 = -1;
        for (int g = 0; g < sps4.size(); g++)
          if (u4::E12(sps4[r], sps4[g]))
          {
            r12 = g;
            break;
          }
        if (r12 >= 0 &&
            !SDarr[i].is_occupied(r12, c)) // meaning it finds a new state
        {
          UNxU4::SlaterDeterminant sd = SDarr[i];
          double phase = (sd.num_hop(r, c, r12, c) % 2 == 0) ? 1 : -1;
          sd.vacate(r, c);
          sd.occupy(r12, c);
          std::pair<size_t, UNxU4::SlaterDeterminant> p(2, sd);
          auto it = std::find(opt_SD.begin(), opt_SD.end(), p);
          if (it == opt_SD.end())
          {
#ifdef NULLSPACE_SPARSE
            ija.emplace_back(opt_SD.size(), i, phase * sps4[r].e12());
#else
            Eigen::RowVectorXd x(SDarr.size());
            x.setZero();
            x(i) = phase * sps4[r].e12();
            mat_temp.push_back(x);
#endif
            opt_SD.push_back(p);
          }
          else
          {
#ifdef NULLSPACE_SPARSE
            ija.emplace_back(std::distance(opt_SD.begin(), it), i,
                             phase * sps4[r].e12());
#else
            mat_temp[std::distance(opt_SD.begin(), it)](i) =
                phase * sps4[r].e12();
#endif
          }
        }

        // action of E23p
        int r23 = -1;
        for (int g = 0; g < sps4.size(); g++)
          if (u4::E23_12(sps4[r], sps4[g]))
          {
            r23 = g;
            break;
          }
        if (r23 >= 0 &&
            !SDarr[i].is_occupied(r23, c)) // meaning it finds a new state
        {
          UNxU4::SlaterDeterminant sd = SDarr[i];
          double phase = (sd.num_hop(r, c, r23, c) % 2 == 0) ? 1 : -1;
          sd.vacate(r, c);
          sd.occupy(r23, c);
          std::pair<size_t, UNxU4::SlaterDeterminant> p(3, sd);
          auto it = std::find(opt_SD.begin(), opt_SD.end(), p);
          if (it == opt_SD.end())
          {
#ifdef NULLSPACE_SPARSE
            ija.emplace_back(opt_SD.size(), i, phase * sps4[r].e23_12());
#else
            Eigen::RowVectorXd x(SDarr.size());
            x.setZero();
            x(i) = phase * sps4[r].e23_12();
            mat_temp.push_back(x);
#endif
            opt_SD.push_back(p);
          }
          else
          {
#ifdef NULLSPACE_SPARSE
            ija.emplace_back(std::distance(opt_SD.begin(), it), i,
                             phase * sps4[r].e23_12());
#else
            mat_temp[std::distance(opt_SD.begin(), it)](i) =
                phase * sps4[r].e23_12();
#endif
          }
        }

        // action of E34p
        int r34 = -1;
        for (int g = 0; g < sps4.size(); g++)
          if (u4::E34_13(sps4[r], sps4[g]))
          {
            r34 = g;
            break;
          }
        if (r34 >= 0 &&
            !SDarr[i].is_occupied(r34, c)) // meaning it finds a new state
        {
          UNxU4::SlaterDeterminant sd = SDarr[i];
          double phase = (sd.num_hop(r, c, r34, c) % 2 == 0) ? 1 : -1;
          sd.vacate(r, c);
          sd.occupy(r34, c);
          std::pair<size_t, UNxU4::SlaterDeterminant> p(4, sd);
          auto it = std::find(opt_SD.begin(), opt_SD.end(), p);
          if (it == opt_SD.end())
          {
#ifdef NULLSPACE_SPARSE
            ija.emplace_back(opt_SD.size(), i, phase * sps4[r].e34_13());
#else
            Eigen::RowVectorXd x(SDarr.size());
            x.setZero();
            x(i) = phase * sps4[r].e34_13();
            mat_temp.push_back(x);
#endif
            opt_SD.push_back(p);
          }
          else
          {
#ifdef NULLSPACE_SPARSE
            ija.emplace_back(std::distance(opt_SD.begin(), it), i,
                             phase * sps4[r].e34_13());
#else
            mat_temp[std::distance(opt_SD.begin(), it)](i) =
                phase * sps4[r].e34_13();
#endif
          }
        }
      }
    }

#ifdef NULLSPACE_SPARSE
    Eigen::SparseMatrix<double> mat(opt_SD.size(), SDarr.size());
    mat.setFromTriplets(ija.begin(), ija.end());
#else
    Eigen::MatrixXd mat(mat_temp.size(), SDarr.size());
    for (size_t i = 0; i < mat_temp.size(); i++)
      mat.row(i) = mat_temp[i];
#endif

    // std::cout << mat << std::endl;

    return mat;
  }

  std::pair<UNxU4::SlaterDeterminants, Eigen::MatrixXd>
  HWS_to_SD(const U3xU4::GammaElement& G, 
    const u3::gelfands& sps3, const u4::gelfands& sps4)
  {
    // int N = (n + 1) * (n + 2) / 2; // shell degeneracy

    UNxU4::SlaterDeterminants SDarr = expand_to_SD(G, sps3, sps4);

    auto mat = RaisingGenerator(SDarr, sps3, sps4);

#if defined(NULLSPACE_SOLVER_KRANS)
    Eigen::MatrixXd expansion = utils::null_space_krans(mat, G.alphamax());
#elif defined(NULLSPACE_SOLVER_SLEPC)
    /* 
    UNtoU3<4> gen;
    gen.set_shell(n);
    gen.reduceU4(x.u4(), N);
    auto multi = gen.multiplicity(x.u3()); 
    */
    Eigen::MatrixXd expansion = utils::null_space_slepc(mat, G.alphamax());
#else
    Eigen::MatrixXd expansion = utils::null_space(mat);
#endif

    // check error
    // std::cout << "The matrix size is " << mat.size() << " with error "
    //          << utils::nullspace_error(mat, expansion) << std::endl;

    return std::make_pair(SDarr, expansion);
  }

  std::filesystem::path get_HWS_file(const U3xU4::GammaElement& G, 
    const u3::gelfands& sps3, const u4::gelfands& sps4)
  {
    assert(!G.vacuum());

#ifdef SAM_DATA_DIR
    const char* sam_data = std::getenv("SAM_DATA_DIR");    
    if (!sam_data)
      throw std::runtime_error(
        "Environment variable SAM_DATA_DIR is not set");

    std::filesystem::path dir = std::filesystem::path(sam_data) / "hws";
#else
    const char* sam_dir = std::getenv("SAM_DIR");
    if (!sam_dir)
      throw std::runtime_error("Environment variable SAM_DIR not set");

    std::filesystem::path dir = std::filesystem::path(sam_dir) / "data/hws";
#endif

    // Create the directory (and parent dirs) if it doesn't exist
    std::filesystem::create_directories(dir);

    std::string filename =
        std::to_string(G.n13()) + "-" + std::to_string(G.n23()) +
        "-" + std::to_string(G.n33()) + "-" +
        std::to_string(G.n14()) + "-" + std::to_string(G.n24()) +
        "-" + std::to_string(G.n34()) + "-" +
        std::to_string(G.n44()) + ".bin";

    std::filesystem::path full_path = dir / filename;

    // If file doesn't exist, create it and save it with data
    if (!std::filesystem::exists(full_path))
    {
#ifdef USE_MPI
      int mpi_rank = 0;
      MPI_Comm_rank(MPI_COMM_WORLD, &mpi_rank);
      std::filesystem::path tmp_path = 
        full_path.string() + ".tmp." + std::to_string(mpi_rank);
#else
      std::filesystem::path tmp_path = full_path.string() + ".tmp";
#endif

      // std::ofstream file(full_path);
      std::ofstream file(tmp_path, std::ios::binary);
      if (!file)
        throw std::runtime_error("Failed to open file for writing: " +
                                 tmp_path.string());

      auto [SDarr, coeffs] = HWS_to_SD(G, sps3, sps4);

      size_t bit_count = SDarr[0].num_sps();
      utils::writeBinary(file, bit_count);

      size_t rows = SDarr.size(), cols = coeffs.cols();
      utils::writeBinary(file, rows);
      utils::writeBinary(file, cols);

      for (size_t i = 0; i < rows; i++)
      {
        std::vector<unsigned long> blocks;
        boost::to_block_range(SDarr[i].bits(), std::back_inserter(blocks));
        utils::writeBinary(file, blocks);

        file.write(reinterpret_cast<const char*>(coeffs.row(i).data()),
                   cols * sizeof(double));
      }

      // for (std::size_t i = 0; i < SDarr.size(); ++i)
      // file << SDarr[i].bits << " " << coeffs.row(i) << '\n';

      file.close();
      std::filesystem::rename(tmp_path, full_path); // atomic: last writer wins, content is identical
    }

    return full_path;
  }

  std::pair<UNxU4::SlaterDeterminants, Eigen::MatrixXd>
  read_HWS_data(const std::filesystem::path& path)
  {
    std::ifstream file(path, std::ios::binary);
    if (!file)
      throw std::runtime_error("Failed to open file for reading: " +
                               path.string());

    size_t bit_count;
    utils::readBinary(file, bit_count);
    size_t block_count = (bit_count + 
      sizeof(unsigned long) * 8 - 1) / (sizeof(unsigned long) * 8);

    size_t rows, cols;
    utils::readBinary(file, rows);
    utils::readBinary(file, cols);

    UNxU4::SlaterDeterminants SDarr;
    SDarr.reserve(rows);

    Eigen::MatrixXd coeffs(rows,cols);

    // std::cout << rows << "," << cols << std::endl;

    for (size_t i = 0; i < rows; i++)
    {      
      std::vector<unsigned long> blocks(block_count);
      utils::readBinary(file, blocks);

      boost::dynamic_bitset<> bits(bit_count);
      boost::from_block_range(blocks.begin(), blocks.end(), bits);
      SDarr.emplace_back(bits);

      std::vector<double> coeff(cols);
      utils::readBinary(file, coeff);
      for (size_t j = 0; j < cols; j++) coeffs(i, j) = coeff[j];
    }

    return std::make_pair(std::move(SDarr), std::move(coeffs));
  }

